/** @type {string | null} */
let currentLocale = DEFAULT_LOCALE;
/** @type {Set<(locale: string) => void>} */
const listeners = new Set();
/** @type {RegExp | null} */
let supportPattern = null;

/** @param {string} value */
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Приводит языковой тег к поддерживаемому коду (en/ru/de/zh/es/ja).
 * @param {unknown} value
 * @returns {string | null}
 */
export function normalizeLocale(value) {
  if (typeof value !== 'string' || !value.trim()) return null;
  const primary = value.trim().toLowerCase().replace('_', '-').split('-')[0];
  if (primary === 'zh') return 'zh';
  return Object.prototype.hasOwnProperty.call(LOCALES, primary) ? primary : null;
}

/** @returns {string | null} */
function storedLocale() {
  try {
    return normalizeLocale(localStorage.getItem(STORAGE_KEY));
  } catch {
    return null;
  }
}

/**
 * Сохранённый язык → язык браузера → английский.
 * @returns {string}
 */
export function detectLocale() {
  const stored = storedLocale();
  if (stored) return stored;

  if (typeof navigator !== 'undefined') {
    const languages = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language];
    for (const language of languages) {
      const normalized = normalizeLocale(language);
      if (normalized) return normalized;
    }
  }
  return DEFAULT_LOCALE;
}

/** @param {string} text @param {Record<string, unknown> | undefined} params */
function interpolate(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] === undefined || params[key] === null ? match : String(params[key]),
  );
}

/**
 * Перевод по ключу. Отсутствующий ключ ищется в английском словаре,
 * затем возвращается сам ключ (удобно замечать пропуски).
 * @param {string} key
 * @param {Record<string, unknown>} [params]
 * @returns {string}
 */
export function t(key, params) {
  const table = MESSAGES[currentLocale] ?? MESSAGES[DEFAULT_LOCALE];
  const fallback = MESSAGES[DEFAULT_LOCALE];
  const text = table[key] ?? fallback[key] ?? key;
  return interpolate(text, params);
}

/** @param {string} [locale] */
export function getLocaleMeta(locale = currentLocale) {
  return LOCALES[locale] ?? LOCALES[DEFAULT_LOCALE];
}

/** @returns {string} */
export function getLocale() {
  return currentLocale;
}

/** @param {string} [locale] */
export function getDictionary(locale = currentLocale) {
  const normalized = normalizeLocale(locale) ?? DEFAULT_LOCALE;
  return MESSAGES[normalized] ?? MESSAGES[DEFAULT_LOCALE];
}

/**
 * Проверяет, что текст бейджа поддержки содержит слово поддержки на любом
 * из поддерживаемых языков. Так локализация не блокирует интерфейс, но
 * произвольная подмена текста по-прежнему обнаруживается.
 * @param {string} text
 */
export function isSupportLabel(text) {
  if (!supportPattern) {
    const words = LOCALE_ORDER.map((locale) => MESSAGES[locale]?.['donation.support'])
      .filter((word) => typeof word === 'string' && word.length > 0)
      .map(escapeRegExp);
    supportPattern = new RegExp(words.join('|'), 'i');
  }
  return supportPattern.test(String(text ?? ''));
}

/**
 * Применяет словарь к статической разметке.
 * @param {ParentNode | Document} [root]
 */
export function applyTranslations(root = document) {
  if (!root?.querySelectorAll) return;
  for (const element of root.querySelectorAll('[data-i18n]')) {
    const key = element.getAttribute('data-i18n');
    if (key) element.textContent = t(key);
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) {
    const key = element.getAttribute('data-i18n-title');
    if (key) element.setAttribute('title', t(key));
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    const key = element.getAttribute('data-i18n-placeholder');
    if (key) element.setAttribute('placeholder', t(key));
  }
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
    const key = element.getAttribute('data-i18n-aria-label');
    if (key) element.setAttribute('aria-label', t(key));
  }
  for (const element of root.querySelectorAll('[data-i18n-content]')) {
    const key = element.getAttribute('data-i18n-content');
    if (key) element.setAttribute('content', t(key));
  }
  for (const element of root.querySelectorAll('[data-i18n-alt]')) {
    const key = element.getAttribute('data-i18n-alt');
    if (key) element.setAttribute('alt', t(key));
  }
}

/** @param {ParentNode | Document} [root] */
function syncLanguageSelectors(root = document) {
  if (!root?.querySelectorAll) return;
  for (const select of root.querySelectorAll('select[data-language-select]')) {
    if (select.dataset.i18nReady !== '1') {
      const options = LOCALE_ORDER.map((locale) => {
        const option = document.createElement('option');
        option.value = locale;
        option.textContent = LOCALES[locale].name;
        return option;
      });
      select.replaceChildren(...options);
      select.dataset.i18nReady = '1';
      select.dataset.i18nBound = '1';
      select.addEventListener('change', () => setLocale(select.value));
    }
    if (select.value !== currentLocale) select.value = currentLocale;
  }
}

/**
 * Переключает язык, сохраняет выбор и обновляет статическую разметку.
 * Динамические модули подписываются на onLocaleChange и перерисовываются.
 * @param {string} locale
 * @param {{persist?: boolean}} [options]
 * @returns {string}
 */
export function setLocale(locale, { persist = true } = {}) {
  const next = normalizeLocale(locale);
  if (!next) return currentLocale;
  currentLocale = next;

  if (typeof document !== 'undefined') {
    document.documentElement.lang = getLocaleMeta(next).htmlLang;
    applyTranslations(document);
    syncLanguageSelectors(document);
  }

  if (persist) {
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* localStorage может быть выключен в приватном режиме */
    }
  }

  for (const listener of listeners) {
    try {
      listener(next);
    } catch (error) {
      console.error('i18n listener failed', error);
    }
  }
  return currentLocale;
}

/**
 * Подписка на смену языка. Возвращает функцию отписки.
 * @param {(locale: string) => void} listener
 * @returns {() => void}
 */
export function onLocaleChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/**
 * Инициализация: определение языка, перевод разметки, привязка селектора.
 * @param {ParentNode | Document} [root]
 * @returns {string}
 */
export function initI18n(root = document) {
  currentLocale = detectLocale();
  if (typeof document !== 'undefined') {
    document.documentElement.lang = getLocaleMeta().htmlLang;
  }
  applyTranslations(root);
  syncLanguageSelectors(root);

  if (typeof window !== 'undefined' && !window.__openDeckI18nStorage) {
    window.__openDeckI18nStorage = true;
    window.addEventListener('storage', (event) => {
      if (event.key === STORAGE_KEY) setLocale(event.newValue || DEFAULT_LOCALE, { persist: false });
    });
  }
  return currentLocale;
}
